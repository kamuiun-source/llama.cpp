struct iq2s_signed_lut_words {
    uint32_t data[81 * 16];
};

static constexpr iq2s_signed_lut_words iq2s_build_signed_lut() {
    iq2s_signed_lut_words out{};
    constexpr int magnitudes[] = {8, 25, 43};
    for (int pattern = 0; pattern < 81; ++pattern) {
        for (int signs = 0; signs < 16; ++signs) {
            int code = pattern;
            uint32_t word = 0;
            for (int lane = 0; lane < 4; ++lane) {
                const int mag = magnitudes[code % 3];
                const int value = (signs >> lane) & 1 ? -mag : mag;
                word |= uint32_t(uint8_t(value)) << (8 * lane);
                code /= 3;
            }
            out.data[16 * pattern + signs] = word;
        }
    }
    return out;
}

static const __device__ iq2s_signed_lut_words iq2s_signed_lut = iq2s_build_signed_lut();
static_assert(sizeof(iq2s_pattern_ids) + sizeof(iq2s_signed_lut) == 7232);

static __device__ __forceinline__ int2 iq2s_lookup_signed(const iq2_s_mmvq_weights & weight, int lane) {
    const auto * qs = reinterpret_cast<const uint8_t *>(&weight.qs);
    const auto * signs = reinterpret_cast<const uint8_t *>(&weight.signs);
    const int grid = qs[lane / 2] | ((int(weight.qh) << (8 - lane)) & 0x300);
    const unsigned patterns = iq2s_pattern_ids[grid];
    const unsigned sign = signs[lane / 2];
    return make_int2(iq2s_signed_lut.data[16 * (patterns & 255) + (sign & 15)],
                     iq2s_signed_lut.data[16 * (patterns >> 8) + (sign >> 4)]);
}

static __device__ __forceinline__ void vec_dot_iq2_s_q8_1_lut_pair(
        const iq2_s_mmvq_weights & up, const iq2_s_mmvq_weights & gate, const block_q8_1 & activation,
        float & up_sum, float & gate_sum) {
    int sum_up[2] = {};
    int sum_gate[2] = {};
#pragma unroll
    for (int l = 0; l < 8; l += 2) {
        const int u0 = get_int_b4(activation.qs, l);
        const int u1 = get_int_b4(activation.qs, l + 1);
        const int2 up_grid = iq2s_lookup_signed(up, l);
        const int2 gate_grid = iq2s_lookup_signed(gate, l);
        const int half = l / 4;
        sum_up[half]   = ggml_cuda_dp4a(up_grid.x, u0, sum_up[half]);
        sum_gate[half] = ggml_cuda_dp4a(gate_grid.x, u0, sum_gate[half]);
        sum_up[half]   = ggml_cuda_dp4a(up_grid.y, u1, sum_up[half]);
        sum_gate[half] = ggml_cuda_dp4a(gate_grid.y, u1, sum_gate[half]);
    }
    const int up_scaled = (sum_up[0]*(up.scales & 0x0F) + sum_up[1]*(up.scales >> 4) + (sum_up[0] + sum_up[1])/2)/4;
    const int gate_scaled = (sum_gate[0]*(gate.scales & 0x0F) + sum_gate[1]*(gate.scales >> 4) + (sum_gate[0] + sum_gate[1])/2)/4;
    const float activation_d = __low2float(activation.ds);
    up_sum   += (__half2float(up.d) * activation_d) * up_scaled;
    gate_sum += (__half2float(gate.d) * activation_d) * gate_scaled;
}
